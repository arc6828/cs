    <script>
        document.addEventListener("DOMContentLoaded", function() {
            const searchInput = document.getElementById("docSearch");
            const rows = document.querySelectorAll(".doc-form-row");
            const boxCoop = document.getElementById("boxCoop");
            const boxIntern = document.getElementById("boxIntern");
            const noAlert = document.getElementById("noDocAlert");
            const counterText = document.getElementById("docCounter");
            const totalCount = <?php echo $totalForms; ?>;

            if (searchInput) {
                searchInput.addEventListener("input", function(e) {
                    const q = e.target.value.trim().toLowerCase();
                    let visibleTotal = 0;
                    let visibleCoop = 0;
                    let visibleIntern = 0;

                    rows.forEach(function(row) {
                        const code = row.getAttribute("data-code") || "";
                        const name = row.getAttribute("data-name") || "";
                        const phase = row.getAttribute("data-phase") || "";
                        const box = row.getAttribute("data-box");

                        const match = (q === "" || code.includes(q) || name.includes(q) || phase.includes(q));

                        if (match) {
                            row.style.display = "flex";
                            visibleTotal++;
                            if (box === "coop") visibleCoop++;
                            if (box === "intern") visibleIntern++;
                        } else {
                            row.style.display = "none";
                        }
                    });

                    // Toggle box headers
                    if (boxCoop) boxCoop.style.display = (visibleCoop > 0) ? "block" : "none";
                    if (boxIntern) boxIntern.style.display = (visibleIntern > 0) ? "block" : "none";

                    // Toggle empty search alert
                    if (noAlert) noAlert.style.display = (visibleTotal === 0) ? "block" : "none";

                    // Update counter
                    if (counterText) {
                        if (q === "") {
                            counterText.textContent = "แสดงทั้งหมด " + totalCount + " รายการ";
                        } else {
                            counterText.textContent = "พบ " + visibleTotal + " จาก " + totalCount + " รายการ";
                        }
                    }
                });
            }
        });
    </script>
